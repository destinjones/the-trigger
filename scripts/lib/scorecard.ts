/**
 * The prediction ledger: record projections, resolve them, render SCOREBOARD.md.
 * Pure functions; scripts/scorecard.ts does the file I/O.
 */

export interface Prediction {
  id: string;
  madeOn: string;
  claim: string;
  resolvesBy: string;
  confidence: number;
  status: 'open' | 'hit' | 'miss';
  resolvedOn: string | null;
  evidenceUrl: string | null;
  weightsVersion: string;
  /** manual: written by a person. projection: logged automatically from a snapshot. */
  kind: 'manual' | 'projection';
  /** For projections: the window the payment must land in. */
  window?: { from: string; to: string };
  snapshot?: string;
}

export interface Ledger {
  $comment?: string;
  predictions: Prediction[];
}

export interface SnapshotLike {
  date: string;
  revision: number;
  weightsVersion: string;
  projectedDate: string;
  confidence: number;
  bandMonths: number;
  readiness: number;
}

function addMonths(iso: string, months: number): string {
  const [y, m, d] = iso.split('-').map(Number) as [number, number, number];
  return new Date(Date.UTC(y, m - 1 + months, d)).toISOString().slice(0, 10);
}

export function quarterOf(iso: string): string {
  const [y, m] = iso.split('-').map(Number) as [number, number];
  return `Q${Math.floor((m - 1) / 3) + 1} ${y}`;
}

/**
 * Log the snapshot's projection if it differs from the last logged projection
 * (different quarter, band, or confidence). Daily re-statements of the same
 * projection are not new predictions.
 */
export function recordProjection(ledger: Ledger, s: SnapshotLike): Ledger {
  const last = [...ledger.predictions].reverse().find((p) => p.kind === 'projection');
  const from = addMonths(s.projectedDate, -s.bandMonths);
  const to = addMonths(s.projectedDate, s.bandMonths);
  if (
    last &&
    last.window?.from.slice(0, 7) === from.slice(0, 7) &&
    last.window?.to.slice(0, 7) === to.slice(0, 7) &&
    last.confidence === s.confidence
  ) {
    return ledger;
  }
  const id = `p-${s.date}-projection`;
  if (ledger.predictions.some((p) => p.id === id)) return ledger; // same-day revision: first statement stands
  const p: Prediction = {
    id,
    madeOn: s.date,
    claim: `First federal AI dividend payment lands between ${from} and ${to} (point estimate ${s.projectedDate}, ${quarterOf(s.projectedDate)})`,
    resolvesBy: to,
    confidence: s.confidence,
    status: 'open',
    resolvedOn: null,
    evidenceUrl: null,
    weightsVersion: s.weightsVersion,
    kind: 'projection',
    window: { from, to },
    snapshot: `data/${s.date}.json`,
  };
  return { ...ledger, predictions: [...ledger.predictions, p] };
}

/** Open predictions whose deadline has passed without a recorded hit become misses. */
export function expire(ledger: Ledger, today: string): Ledger {
  return {
    ...ledger,
    predictions: ledger.predictions.map((p) =>
      p.status === 'open' && p.resolvesBy < today ? { ...p, status: 'miss', resolvedOn: today } : p,
    ),
  };
}

/** Mean squared error of confidence vs outcome over resolved predictions. Lower is better; 0.25 is a coin flip at 50%. */
export function brier(ps: readonly Prediction[]): number | null {
  const r = ps.filter((p) => p.status !== 'open');
  if (r.length === 0) return null;
  return r.reduce((a, p) => a + (p.confidence - (p.status === 'hit' ? 1 : 0)) ** 2, 0) / r.length;
}

export function renderScoreboard(ledger: Ledger, today: string): string {
  const ps = ledger.predictions;
  const open = ps.filter((p) => p.status === 'open');
  const resolved = ps.filter((p) => p.status !== 'open');
  const hits = resolved.filter((p) => p.status === 'hit').length;
  const b = brier(ps);
  const row = (p: Prediction) =>
    `| ${p.madeOn} | ${p.claim} | ${Math.round(p.confidence * 100)}% | ${p.resolvesBy} | ${p.status}${p.evidenceUrl ? ` ([evidence](${p.evidenceUrl}))` : ''} | ${p.kind} |`;
  const head = '| Made | Claim | Confidence | Resolves by | Status | Kind |\n|---|---|---|---|---|---|';
  return [
    '<!-- Generated by `pnpm scorecard` from predictions/ledger.json. Do not hand-edit. -->',
    '# Scoreboard',
    '',
    'Every projection The Trigger makes is logged here when it is made and graded when it resolves.',
    'A projection is logged whenever its window or confidence changes; daily restatements of the same projection are not counted twice.',
    '',
    `As of ${today}: **${ps.length}** predictions, **${resolved.length}** resolved, **${hits}** hit, **${resolved.length - hits}** missed.` +
      (b === null ? ' Brier score: n/a until something resolves.' : ` Brier score: **${b.toFixed(3)}** (lower is better; always saying 50% scores 0.250).`),
    '',
    '## Open',
    '',
    open.length ? [head, ...open.map(row)].join('\n') : '_None._',
    '',
    '## Resolved',
    '',
    resolved.length ? [head, ...resolved.map(row)].join('\n') : '_None yet._',
    '',
    '## Rules',
    '',
    '- The ledger is append-only. Claims, dates and confidence are never edited after the fact.',
    '- A prediction resolves as a **hit** only with an `evidenceUrl` to the upstream record (for example the Treasury announcement or the enacted law).',
    '- An open prediction past its `resolvesBy` date is marked a **miss** automatically.',
    '- Confidence here is the tracker\'s formula output, not a calibrated probability. This page is how we find out how wrong it is.',
    '',
  ].join('\n');
}
